#!/usr/bin/env python3
"""Regenerates Sources/OceanChecks/WebWorldReference.swift from the original world.ts.

Usage: python3 Tools/web-reference/gen-swift.py <patched ascii-spiders clone> > Sources/OceanChecks/WebWorldReference.swift
(see README.md for the clone and the patch).
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# name, seed, W, H, cw, ch, roster (None: the demo page's default cast), settled, steps, checkpoints
RUNS = [
    ("demo", 7, 1800, 1169, 13, 19, None, False, 36000, [600, 36000]),
    ("roster, settled", 22, 700, 450, 9, 13, ["nephila", "argiope", "araneus", "nephila", "argiope"], True, 3600, [3600]),
]


def run(clone, seed, W, H, cw, ch, spiders, settled, steps, checkpoints):
    opts = {}
    if spiders is not None:
        opts["spiders"] = spiders
    if settled:
        opts["settled"] = True
    args = ["node", os.path.join(HERE, "world-ref.mjs"), *map(str, (seed, W, H, cw, ch, steps)), ",".join(map(str, checkpoints))]
    env = dict(os.environ, WEB_OPTS=json.dumps(opts, separators=(",", ":")))
    out = subprocess.run(args, cwd=clone, env=env, check=True, capture_output=True, text=True).stdout
    return json.loads(out), args[2:], opts


def lit(v):
    v = float(v)
    return str(int(v)) if v.is_integer() else repr(v)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    clone = sys.argv[1]
    out = [
        "import OceanKit",
        "",
        "// Generated by Tools/web-reference/gen-swift.py: the original world.ts run by world-ref.mjs on the WebRandom",
        "// stream (see webWorldMatchesOriginal). Each checkpoint lists webWorldFeatures in order; `next` is",
        "// Math.random() once more after the last step, so both sides have drawn from the stream equally often.",
        "",
        "struct WebWorldRun {",
        "    var name: String, seed: UInt64, width: Double, height: Double, cw: Double, ch: Double",
        "    var spiders: [SpiderKind]?, settled: Bool",
        "    var checkpoints: [(step: Int, labels: [String], values: [Double])]",
        "    var next: Double",
        "}",
        "",
        "let webWorldReference: [WebWorldRun] = [",
    ]
    for name, seed, W, H, cw, ch, spiders, settled, steps, cps in RUNS:
        r, args, opts = run(clone, seed, W, H, cw, ch, spiders, settled, steps, cps)
        out.append(f"    // WEB_OPTS='{json.dumps(opts, separators=(',', ':'))}' node world-ref.mjs {' '.join(args)}")
        sp = "nil" if spiders is None else "[" + ", ".join("." + s for s in spiders) + "]"
        out.append(f'    WebWorldRun(name: "{name}", seed: {seed}, width: {W}, height: {H}, cw: {cw}, ch: {ch}, '
                   f'spiders: {sp}, settled: {"true" if settled else "false"}, checkpoints: [')
        for k in sorted((k for k in r if k.isdigit()), key=int):
            labels = [x[0] for x in r[k]]
            vals = [x[1] for x in r[k]]
            out.append(f"        ({k}, [")
            for i in range(0, len(labels), 6):
                out.append("            " + ", ".join(f'"{l}"' for l in labels[i:i + 6]) + ",")
            out.append("        ], [")
            for i in range(0, len(vals), 6):
                out.append("            " + ", ".join(lit(v) for v in vals[i:i + 6]) + ",")
            out.append("        ]),")
        out.append(f"    ], next: {r['next']!r}),")
    out.append("]")
    print("\n".join(out))


if __name__ == "__main__":
    main()
