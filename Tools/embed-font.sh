#!/bin/zsh
# Regenerates Sources/OceanKit/Render/GeistMonoData.swift from Resources/GeistMono.ttf.
# The font is compiled in so the app needs no SwiftPM resource bundle.
set -euo pipefail
cd "${0:A:h}/.."
{
  echo "// Generated by Tools/embed-font.sh from Resources/GeistMono.ttf (Geist Mono, SIL OFL 1.1; see Resources/OFL.txt)."
  echo "// swiftlint:disable all"
  echo "enum GeistMonoData {"
  printf '    static let base64 = "'
  base64 -i Resources/GeistMono.ttf | tr -d '\n'
  echo '"'
  echo "}"
} > Sources/OceanKit/Render/GeistMonoData.swift
echo "wrote Sources/OceanKit/Render/GeistMonoData.swift"
